<?php

declare(strict_types=1);

namespace Database\Seeders;

use App\Models\Permission;
use App\Models\Role;
use App\Models\User;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\Hash;

final class UserSeeder extends Seeder
{
    /**
     * Run the database seeds.
     */
    public function run(): void
    {
        /*
        |--------------------------------------------------------------------------
        | Get Roles
        |--------------------------------------------------------------------------
        */

        $adminRole = Role::query()
            ->where('slug', 'admin')
            ->firstOrFail();

        $clientRole = Role::query()
            ->where('slug', 'client')
            ->firstOrFail();


        /*
        |--------------------------------------------------------------------------
        | Admin User
        |--------------------------------------------------------------------------
        */

        $admin = User::updateOrCreate(
            [
                'email' => 'admin@gmail.com',
            ],
            [
                'first_name' => 'Admin',
                'last_name' => 'User',
                'phone' => null,
                'address' => null,
                'password' => Hash::make('12345678'),
                'status' => 'active',
                'email_verified_at' => now(),
            ],
        );


        /*
        |--------------------------------------------------------------------------
        | Assign Admin Role
        |--------------------------------------------------------------------------
        */

        $admin->roles()->sync([
            $adminRole->id,
        ]);


        /*
        |--------------------------------------------------------------------------
        | Admin Gets All Permissions
        |--------------------------------------------------------------------------
        */

        $allPermissionIds = Permission::query()
            ->pluck('id')
            ->all();

        $adminRole->permissions()->sync(
            $allPermissionIds,
        );


        /*
        |--------------------------------------------------------------------------
        | Client User
        |--------------------------------------------------------------------------
        */

        $client = User::updateOrCreate(
            [
                'email' => 'client@gmail.com',
            ],
            [
                'first_name' => 'Demo',
                'last_name' => 'Client',
                'phone' => null,
                'address' => null,
                'password' => Hash::make('12345678'),
                'status' => 'active',
                'email_verified_at' => now(),
            ],
        );


        /*
        |--------------------------------------------------------------------------
        | Assign Client Role
        |--------------------------------------------------------------------------
        */

        $client->roles()->sync([
            $clientRole->id,
        ]);


        /*
        |--------------------------------------------------------------------------
        | Client Permissions
        |--------------------------------------------------------------------------
        |
        | Only customer-facing permissions are assigned.
        | Admin-only permissions are excluded.
        |
        */

        $clientPermissions = [

            /*
            |--------------------------------------------------------------------------
            | Dashboard
            |--------------------------------------------------------------------------
            */

            'view-dashboard',


            /*
            |--------------------------------------------------------------------------
            | Profile
            |--------------------------------------------------------------------------
            */

            'view-profile',


            /*
            |--------------------------------------------------------------------------
            | Notifications
            |--------------------------------------------------------------------------
            */

            'view-notifications',


            /*
            |--------------------------------------------------------------------------
            | Services
            |--------------------------------------------------------------------------
            */

            'view-services',
            'view-service-details',


            /*
            |--------------------------------------------------------------------------
            | Ecommerce - Products
            |--------------------------------------------------------------------------
            */

            'view-products',


            /*
            |--------------------------------------------------------------------------
            | Ecommerce - Categories
            |--------------------------------------------------------------------------
            */

            'view-categories',


            /*
            |--------------------------------------------------------------------------
            | Ecommerce - Cart
            |--------------------------------------------------------------------------
            */

            'view-cart',
            'manage-cart',


            /*
            |--------------------------------------------------------------------------
            | Ecommerce - Orders
            |--------------------------------------------------------------------------
            */

            'create-order',
            'view-orders',
            'view-order-details',


            /*
            |--------------------------------------------------------------------------
            | General Payments
            |--------------------------------------------------------------------------
            */

            'view-payments',


            /*
            |--------------------------------------------------------------------------
            | General Tracking
            |--------------------------------------------------------------------------
            */

            'view-tracking',
            'view-tracking-details',


            /*
            |--------------------------------------------------------------------------
            | Invoices
            |--------------------------------------------------------------------------
            */

            'view-invoices',


            /*
            |--------------------------------------------------------------------------
            | Smart Buy - Customer
            |--------------------------------------------------------------------------
            */

            'my-smart-buy',
            'my-smart-buy-details',
            'my-smart-buy-create',
            'my-smart-buy-quote',
            'my-smart-buy-payment',
            'my-smart-buy-tracking',
        ];


        /*
        |--------------------------------------------------------------------------
        | Remove Duplicate Permissions
        |--------------------------------------------------------------------------
        */

        $clientPermissions = array_values(
            array_unique($clientPermissions),
        );


        /*
        |--------------------------------------------------------------------------
        | Get Client Permission IDs
        |--------------------------------------------------------------------------
        */

        $clientPermissionIds = Permission::query()
            ->whereIn('slug', $clientPermissions)
            ->pluck('id')
            ->all();


        /*
        |--------------------------------------------------------------------------
        | Assign Permissions To Client Role
        |--------------------------------------------------------------------------
        */

        $clientRole->permissions()->sync(
            $clientPermissionIds,
        );
    }
}
